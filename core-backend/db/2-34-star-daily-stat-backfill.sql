-- 스타 인사이트 일별 통계 과거분 채우기 (2-34차, 선택 실행)
--
-- 2-34-star-daily-stat.sql 다음에, 사용량이 적은 시간대에 수동 실행한다.
-- 최근 1년(어제까지)의 방문·즐겨찾기·좋아요·게시물을 날짜별로 다시 쓴다. 여러 번 실행해도 결과는 같다.
-- 글로벌 랭킹(GLOBAL_RANK)은 과거 기록이 없어 채우지 않는다.
--
-- 주의: WH_AD_LOG 는 행이 많다. 실행 전 인덱스를 확인할 것 — CREATED_DATE 로 시작하는 인덱스가 없으면
--       첫 문장이 전체 스캔이 된다. 필요하면 아래 인덱스를 먼저 만든다(사용자 승인 후).
--   SHOW INDEX FROM WH_AD_LOG;
--   -- CREATE INDEX IDX_WH_AD_LOG_DATE ON WH_AD_LOG (CREATED_DATE, ACTION, PRS_ID);
-- =========================================================

SET @from_date = CURDATE() - INTERVAL 366 DAY;
SET @to_date = CURDATE();

INSERT INTO WH_STAR_DAILY_STAT (STAT_DATE, PRS_ID, VISIT_CNT)
SELECT DATE(CREATED_DATE), PRS_ID, COUNT(*)
FROM WH_AD_LOG
WHERE ACTION = 'IMPRESSION' AND PRS_ID IS NOT NULL
  AND CREATED_DATE >= @from_date AND CREATED_DATE < @to_date
GROUP BY DATE(CREATED_DATE), PRS_ID
ON DUPLICATE KEY UPDATE VISIT_CNT = VALUES(VISIT_CNT);

INSERT INTO WH_STAR_DAILY_STAT (STAT_DATE, PRS_ID, FOLLOW_CNT)
SELECT DATE(CREATED_DATE), PRS_ID, COUNT(*)
FROM WH_FOLLOWER_LOG
WHERE ACTION = 'FOLLOW' AND PRS_ID IS NOT NULL
  AND CREATED_DATE >= @from_date AND CREATED_DATE < @to_date
GROUP BY DATE(CREATED_DATE), PRS_ID
ON DUPLICATE KEY UPDATE FOLLOW_CNT = VALUES(FOLLOW_CNT);

INSERT INTO WH_STAR_DAILY_STAT (STAT_DATE, PRS_ID, UNFOLLOW_CNT)
SELECT DATE(CREATED_DATE), PRS_ID, COUNT(*)
FROM WH_FOLLOWER_LOG
WHERE ACTION = 'UNFOLLOW' AND PRS_ID IS NOT NULL
  AND CREATED_DATE >= @from_date AND CREATED_DATE < @to_date
GROUP BY DATE(CREATED_DATE), PRS_ID
ON DUPLICATE KEY UPDATE UNFOLLOW_CNT = VALUES(UNFOLLOW_CNT);

INSERT INTO WH_STAR_DAILY_STAT (STAT_DATE, PRS_ID, LIKE_CNT)
SELECT DATE(CREATED_DATE), PRS_ID, COUNT(*)
FROM WH_LIKE_LOG
WHERE ACTION = 'LIKE' AND PRS_ID IS NOT NULL
  AND CREATED_DATE >= @from_date AND CREATED_DATE < @to_date
GROUP BY DATE(CREATED_DATE), PRS_ID
ON DUPLICATE KEY UPDATE LIKE_CNT = VALUES(LIKE_CNT);

INSERT INTO WH_STAR_DAILY_STAT (STAT_DATE, PRS_ID, POST_CNT)
SELECT DATE(CREATED_DATE), PRS_ID, COUNT(*)
FROM WH_STAR_CONTENT
WHERE PRS_ID IS NOT NULL
  AND CREATED_DATE >= @from_date AND CREATED_DATE < @to_date
GROUP BY DATE(CREATED_DATE), PRS_ID
ON DUPLICATE KEY UPDATE POST_CNT = VALUES(POST_CNT);
